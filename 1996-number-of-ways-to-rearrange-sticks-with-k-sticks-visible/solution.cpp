class Solution {
public:
    int mod = 1e9 + 7;
    int rearrangeSticks(int n, int k) {
        vector<vector<long long>> dp(n + 1, vector<long long>(k + 1, 0));
        dp[0][0] = 1;
        for(int i = 1; i <= n; i++) {
            for(int j = 1; j <= min(i, k); j++) {
                dp[i][j] = (dp[i - 1][j] * (i - 1) + dp[i - 1][j - 1]) % mod;
            }
        }
        return dp[n][k];
    }
};

// Idea:
// n = 4, k = 1
// [4] 1  2  3      => dp[0][0] * P(3, 3)
//  1 [4] 2  3      => dp[1][0] * P(3, 2)
//  1  2 [4] 3      => dp[2][0] * P(3, 1)
//  1  2  3 [4]     => dp[3][0] * P(3, 0)
// -------------------------------------------------------
// n = 5, k = 1
// [5] 1  2  3  4   => dp[0][0] * [P(4, 4) = 4 * P(3, 3)]
//  1 [5] 2  3  4   => dp[1][0] * [P(4, 3) = 4 * P(3, 2)]
//  1  2 [5] 3  4   => dp[2][0] * [P(4, 2) = 4 * P(3, 1)]
//  1  2  3 [5] 4   => dp[3][0] * [P(4, 1) = 4 * P(3, 0)]
//  1  2  3  4 [5]  => dp[4][0] * [P(4, 0) = 1          ]
// -------------------------------------------------------
// => dp[n][k] = dp[n - 1][k] * (n - 1) + dp[n - 1][k - 1]
